USE classicmodels;

-- ------------------------------------------------------------------------------
-- 1. Sales Representative Leaderboard & Revenue Attribution
-- Computes individual sales rep commercial contribution, account load, and AOV.
-- ------------------------------------------------------------------------------
SELECT 
    e.employeeNumber,
    CONCAT(e.firstName, ' ', e.lastName) AS sales_representative_name,
    e.jobTitle,
    off.city AS office_city,
    off.country AS office_country,
    COUNT(DISTINCT c.customerNumber) AS assigned_customer_count,
    COUNT(DISTINCT o.orderNumber) AS orders_closed_count,
    SUM(od.quantityOrdered) AS units_sold,
    ROUND(SUM(od.quantityOrdered * od.priceEach), 2) AS attributed_realized_revenue,
    ROUND(SUM(od.quantityOrdered * od.priceEach) / SUM(SUM(od.quantityOrdered * od.priceEach)) OVER () * 100, 2) AS team_revenue_share_pct,
    ROUND(SUM(od.quantityOrdered * (od.priceEach - p.buyPrice)), 2) AS attributed_gross_profit,
    ROUND(SUM(od.quantityOrdered * (od.priceEach - p.buyPrice)) / SUM(od.quantityOrdered * od.priceEach) * 100, 2) AS gross_margin_pct,
    ROUND(SUM(od.quantityOrdered * od.priceEach) / COUNT(DISTINCT o.orderNumber), 2) AS avg_deal_size_aov,
    ROUND(SUM(od.quantityOrdered * od.priceEach) / COUNT(DISTINCT c.customerNumber), 2) AS revenue_per_assigned_account,
    DENSE_RANK() OVER (ORDER BY SUM(od.quantityOrdered * od.priceEach) DESC) AS sales_rank
FROM employees e
JOIN offices off ON e.officeCode = off.officeCode
LEFT JOIN customers c ON e.employeeNumber = c.salesRepEmployeeNumber
LEFT JOIN orders o ON c.customerNumber = o.customerNumber AND o.status = 'Shipped'
LEFT JOIN orderdetails od ON o.orderNumber = od.orderNumber
LEFT JOIN products p ON od.productCode = p.productCode
WHERE e.jobTitle = 'Sales Rep'
GROUP BY e.employeeNumber, e.firstName, e.lastName, e.jobTitle, off.city, off.country
ORDER BY attributed_realized_revenue DESC;

-- ------------------------------------------------------------------------------
-- 2. Management Hierarchy & Rollup Analysis
-- Demonstrates multi-level sales reporting hierarchy up to Executive Leadership.
-- ------------------------------------------------------------------------------
WITH RECURSIVE employee_hierarchy AS (
    -- Anchor: Top executive (Diane Murphy, President)
    SELECT 
        employeeNumber,
        CONCAT(firstName, ' ', lastName) AS employee_name,
        reportsTo,
        jobTitle,
        1 AS org_level,
        CAST(CONCAT(firstName, ' ', lastName) AS CHAR(1000)) AS hierarchy_path
    FROM employees
    WHERE reportsTo IS NULL
    
    UNION ALL
    
    -- Recursive step: Direct reports
    SELECT 
        e.employeeNumber,
        CONCAT(e.firstName, ' ', e.lastName),
        e.reportsTo,
        e.jobTitle,
        eh.org_level + 1,
        CONCAT(eh.hierarchy_path, ' -> ', e.firstName, ' ', e.lastName)
    FROM employees e
    JOIN employee_hierarchy eh ON e.reportsTo = eh.employeeNumber
)
SELECT 
    org_level,
    employeeNumber,
    employee_name,
    jobTitle,
    hierarchy_path
FROM employee_hierarchy
ORDER BY org_level, employeeNumber;

-- ------------------------------------------------------------------------------
-- 3. Sales Manager Team Rollup Performance
-- Aggregates revenue generated by the sales reps reporting to each regional sales manager.
-- ------------------------------------------------------------------------------
SELECT 
    mgr.employeeNumber AS manager_id,
    CONCAT(mgr.firstName, ' ', mgr.lastName) AS sales_manager_name,
    mgr.jobTitle AS manager_title,
    COUNT(DISTINCT rep.employeeNumber) AS direct_sales_reps_count,
    COUNT(DISTINCT c.customerNumber) AS total_managed_customers,
    COUNT(DISTINCT o.orderNumber) AS total_team_orders,
    ROUND(SUM(od.quantityOrdered * od.priceEach), 2) AS team_attributed_revenue,
    ROUND(SUM(od.quantityOrdered * (od.priceEach - p.buyPrice)), 2) AS team_gross_profit,
    ROUND(SUM(od.quantityOrdered * (od.priceEach - p.buyPrice)) / SUM(od.quantityOrdered * od.priceEach) * 100, 2) AS team_margin_pct
FROM employees mgr
JOIN employees rep ON mgr.employeeNumber = rep.reportsTo
LEFT JOIN customers c ON rep.employeeNumber = c.salesRepEmployeeNumber
LEFT JOIN orders o ON c.customerNumber = o.customerNumber AND o.status = 'Shipped'
LEFT JOIN orderdetails od ON o.orderNumber = od.orderNumber
LEFT JOIN products p ON od.productCode = p.productCode
GROUP BY mgr.employeeNumber, mgr.firstName, mgr.lastName, mgr.jobTitle
HAVING team_attributed_revenue > 0
ORDER BY team_attributed_revenue DESC;
